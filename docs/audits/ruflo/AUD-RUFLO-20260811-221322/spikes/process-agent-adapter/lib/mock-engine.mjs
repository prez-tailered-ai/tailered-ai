import { createHash } from "node:crypto";

export const ENGINE_ID = "mock-deterministic";
export const PROVIDER_ID = "local.mock";

/**
 * The concrete model this adapter actually used.
 * Tailered's registry ships symbolic aliases ("best-available"), so an adapter
 * MUST resolve alias -> concrete identity and report the concrete one back.
 * Tailered validates neither, which is the gap documented as RUF-712.
 */
const ALIAS_TO_CONCRETE = Object.freeze({
  "best-available": "mock-frontier-1.0",
  "mid-available": "mock-mid-1.0",
  "cheap-available": "mock-cheap-1.0",
});

export function resolveModel(alias) {
  const concrete = ALIAS_TO_CONCRETE[alias];
  if (concrete === undefined) {
    throw new Error(`Unknown model alias from tailered.config.json: ${alias}`);
  }
  return concrete;
}

/** Pure: (request) -> payload. Same request in, byte-identical payload out. */
export function generate(request) {
  switch (request.taskKind) {
    case "testgen":
      return {
        tests: [
          {
            id: "spike-unit",
            title: "Product unit tests pass",
            command: process.execPath,
            args: ["--test", "test/todo.test.mjs"],
            cwd: "product",
          },
        ],
      };
    case "codegen":
      return { files: codegenFiles(request) };
    case "critique":
      return { violations: [], flags: [] };
    case "adr_draft":
      return {
        title: "Adopt a bounded process-agent adapter",
        context:
          "The company needs an implementation seat that cannot mutate the repository it is reasoning about.",
        decision:
          "Run the implementation seat as a one-shot subprocess that receives a read-only snapshot and returns whole files.",
        alternativesRejected: [
          "Give the orchestrator write access to the repository working tree.",
          "Let the orchestrator report its own success without an independent postcondition read.",
        ],
        consequences: [
          "The repository stays the sole source of truth.",
          "Every agent call carries measured usage and a provenance record.",
        ],
      };
    case "narrate":
    case "judge":
      return {};
    default:
      throw new Error(`Unsupported taskKind: ${request.taskKind}`);
  }
}

function codegenFiles(request) {
  // Content is derived only from the request, so the payload is reproducible.
  const specHash = createHash("sha256")
    .update(request.spec)
    .digest("hex")
    .slice(0, 12);
  return [
    {
      path: "product/app.mjs",
      content:
        `// generated by ${ENGINE_ID} for spec ${specHash}\n` +
        `export function addTodo(todos, title, id) {\n` +
        `  const cleanTitle = title.trim();\n` +
        `  if (!cleanTitle) throw new TypeError("Todo title is required.");\n` +
        `  return [...todos, { id, title: cleanTitle, completed: false }];\n` +
        `}\n`,
    },
    {
      path: "product/index.html",
      content:
        `<!doctype html>\n<html lang="en"><head><meta charset="utf-8">` +
        `<title>Tasks</title></head><body><main id="todo-form"></main>` +
        `<script type="module" src="./app.mjs"></script></body></html>\n`,
    },
  ];
}
